    case rightEye = "head-right-eye"
    case leftEye = "head-left-eye"
    case rightForehead = "head-right-forehead"
    case leftForehead = "head-left-forehead"
    case rightJaw = "head-right-jaw"
    case leftJaw = "head-left-jaw"
}
